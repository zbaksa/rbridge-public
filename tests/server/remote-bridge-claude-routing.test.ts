import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {afterEach,describe,expect,it,vi} from 'vitest';
import {createRemoteBridgeStore} from '../../src/server/remoteBridgeStore.js';
import {createRemoteBridgeWorker} from '../../src/server/remoteBridgeWorker.js';
import {remoteBridgeRequestV2Digest,parseRemoteBridgeRequestV2} from '../../src/domain/remoteBridgeStage2Protocol.js';

const roots:string[]=[];
const now=()=>new Date('2026-10-31T22:00:00.000Z');
async function store(){const root=await mkdtemp(join(tmpdir(),'bridge-claude-routing-'));roots.push(root);return createRemoteBridgeStore(root,now);}
afterEach(async()=>await Promise.all(roots.splice(0).map(p=>rm(p,{recursive:true,force:true}))));
const TRANSPORT={repository:'example/rbridge-control',authorLogin:'bridge-owner'} as const;
const request=(requestId='claude.health.1',operation:Record<string,unknown>={kind:'HEALTH',action:'STATUS'})=>({
  schema:'COCWIN_REMOTE_BRIDGE_REQUEST_V2',requestId,createdAt:'2026-10-31T21:59:00.000Z',
  expiresAt:'2026-10-31T22:07:00.000Z',operation,
});
const raw=(value:unknown)=>JSON.stringify(value);
const fence='\x60\x60\x60';
const fenced=(value:unknown)=>fence+'json\n'+JSON.stringify(value,null,2)+'\n'+fence+'\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01KHxVCpSsZTSbbbhTxPwb4r)_';
const issue=(number:number,value:ReturnType<typeof request>,body=fenced(value),authorLogin='bridge-owner')=>({
  number,title:'[COCWIN BRIDGE REQUEST] '+value.requestId,body,authorLogin,url:'https://github.com/example/rbridge-control/issues/'+number,
});
const controller=()=>({submit:vi.fn(),status:vi.fn(),result:vi.fn()});
const health={schema:'COCWIN_REMOTE_BRIDGE_HEALTH_V2',status:'PASS',releaseSha:'a'.repeat(40),
  uptimeMs:10,queueCount:11,sessionCount:0,transferCount:4,lastGitHubPollAt:null};

describe('Claude fenced RBridge request routing — SOURCE ONLY',()=>{
  it('never accepts Claude fence unless worker explicitly opts in',async()=>{
    const db=await store(),publish=vi.fn(),ctl=controller(),snapshot=vi.fn(()=>health);
    const worker=createRemoteBridgeWorker({...TRANSPORT,now,store:db,github:{
      listOpenRequests:async()=>[issue(700,request())],publishResult:publish},
      controller:ctl,health:{snapshot},
    });
    expect(await worker.runOnce()).toMatchObject({seen:1,blocked:1,published:1});
    expect(snapshot).not.toHaveBeenCalled();
    expect(ctl.submit).not.toHaveBeenCalled();
    expect(publish.mock.calls[0]![1]).toMatchObject({status:'BLOCKED',reason:'REMOTE_BRIDGE_BODY_JSON_INVALID'});
  });

  it('routes exact opt-in Claude fence into V2 HEALTH without controller effects',async()=>{
    const value=request(),db=await store(),publish=vi.fn(),snapshot=vi.fn(()=>health),ctl=controller(),f=issue(701,value);
    const worker=createRemoteBridgeWorker({...TRANSPORT,allowClaudeFence:true,now,store:db,github:{
      listOpenRequests:async()=>[f],publishResult:publish},
      controller:ctl,health:{snapshot},
    });
    expect(await worker.runOnce()).toMatchObject({seen:1,blocked:0,published:1,pending:0,errors:0});
    expect(snapshot).toHaveBeenCalledOnce();expect(ctl.submit).not.toHaveBeenCalled();
    const expected=remoteBridgeRequestV2Digest(parseRemoteBridgeRequestV2({
      title:f.title,body:raw(value),author:f.authorLogin,repository:TRANSPORT.repository,
      expectedAuthor:TRANSPORT.authorLogin,expectedRepository:TRANSPORT.repository,now:now(),
    }));
    expect(publish.mock.calls[0]![1]).toMatchObject({
      schema:'COCWIN_REMOTE_BRIDGE_RESULT_V2',status:'PASS',requestSha256:expected,operationResult:health,
    });
    expect((await db.get('claude.health.1'))?.phase).toBe('PUBLISHED');
  });

  it('replays an existing pure JSON V2 result through signed Claude format without rerun',async()=>{
    const db=await store(),value=request('claude.replay.1'),snapshot=vi.fn(()=>health),publish=vi.fn();
    const first=createRemoteBridgeWorker({...TRANSPORT,now,store:db,
      github:{listOpenRequests:async()=>[issue(702,value,raw(value))],publishResult:publish},
      controller:controller(),health:{snapshot}});
    expect(await first.runOnce()).toMatchObject({published:1});
    const second=createRemoteBridgeWorker({...TRANSPORT,allowClaudeFence:true,now,store:db,
      github:{listOpenRequests:async()=>[issue(703,value)],publishResult:publish},
      controller:controller(),health:{snapshot}});
    expect(await second.runOnce()).toMatchObject({published:1});
    expect(snapshot).toHaveBeenCalledOnce();
    expect(publish.mock.calls[1]![1]).toMatchObject({schema:'COCWIN_REMOTE_BRIDGE_RESULT_V2',status:'PASS'});
  });

  it('preserves protected APP_RUN HOLD before controller.submit when signed JSON is enabled',async()=>{
    const db=await store(),hold=vi.fn(async()=>true),ctl=controller(),pub=vi.fn();
    const app=request('claude.held.1',{kind:'APP_RUN',appId:'dart',jobId:'claude-held-1',
      payload:{tool:'probe',cwd:'/home/dart/backend',args:[],timeout_ms:10000,max_bytes:4096}});
    const worker=createRemoteBridgeWorker({...TRANSPORT,allowClaudeFence:true,now,store:db,
      github:{listOpenRequests:async()=>[issue(704,app)],publishResult:pub},
      controller:ctl,admissionHold:hold});
    expect(await worker.runOnce()).toMatchObject({pending:1,published:0,blocked:0});
    expect(hold).toHaveBeenCalledOnce();
    expect(hold.mock.calls[0]![0]).toMatchObject({appId:'dart',requestId:'claude.held.1'});
    expect(ctl.submit).not.toHaveBeenCalled();expect(pub).not.toHaveBeenCalled();
    expect((await db.get('claude.held.1'))?.phase).toBe('WAITING');
  });

  it('rejects forged author, malformed signature, and second JSON block without effects',async()=>{
    for(const [number,body,author] of [
      [705,fenced(request()),'attacker'],
      [706,fenced(request()).replace('claude.ai/code','untrusted.example'),'bridge-owner'],
      [707,fenced(request())+'\n'+fence+'json\n{}\n'+fence,'bridge-owner'],
    ] as const){
      const db=await store(),ctl=controller(),pub=vi.fn(),snap=vi.fn(()=>health);
      const worker=createRemoteBridgeWorker({...TRANSPORT,allowClaudeFence:true,now,store:db,
        github:{listOpenRequests:async()=>[issue(number,request(),body,author)],publishResult:pub},
        controller:ctl,health:{snapshot:snap}});
      expect(await worker.runOnce()).toMatchObject({blocked:1,published:1});
      expect(snap).not.toHaveBeenCalled();expect(ctl.submit).not.toHaveBeenCalled();
    }
  });
});
