import {describe,expect,it} from 'vitest';
import {extractClaudeFencedIssueBody,parseRemoteBridgeRequestV2,remoteBridgeRequestV2Digest} from '../../src/domain/remoteBridgeStage2Protocol.js';

const FENCE='\x60\x60\x60';
const RAW=JSON.stringify({
  schema:'COCWIN_REMOTE_BRIDGE_REQUEST_V2',
  requestId:'r3.claude.1',
  createdAt:'2026-10-31T21:59:00.000Z',
  expiresAt:'2026-10-31T22:07:00.000Z',
  operation:{kind:'HEALTH',action:'STATUS'},
});
const SIGNATURE='\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const SESSION_SIGNATURE='\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01KHxVCpSsZTSbbbhTxPwb4r)_';
const BASE={
  title:'[COCWIN BRIDGE REQUEST] r3.claude.1',
  author:'bridge-owner',repository:'example/rbridge-control',
  expectedAuthor:'bridge-owner',expectedRepository:'example/rbridge-control',
  now:new Date('2026-10-31T22:00:00.000Z'),
};
function fenced(inner:string,tail=''){return FENCE+'json\n'+inner+'\n'+FENCE+tail;}
function parse(body:string,allowClaudeFence?:boolean){
  return parseRemoteBridgeRequestV2({...BASE,body,...(allowClaudeFence===undefined?{}:{allowClaudeFence})});
}

describe('RBridge V11 Claude fenced issue body — disabled by default',()=>{
  it('preserves strict legacy JSON and accepts fenced input only with explicit opt-in',()=>{
    const legacy=parse(RAW),enabled=parse(fenced(RAW,SIGNATURE),true);
    expect(parse(RAW,true)).toEqual(legacy);
    expect(enabled).toEqual(legacy);
    expect(remoteBridgeRequestV2Digest(enabled)).toBe(remoteBridgeRequestV2Digest(legacy));
    expect(()=>parse(fenced(RAW,SIGNATURE))).toThrow(/REMOTE_BRIDGE_V2_BODY_JSON_INVALID/);
  });
  it('accepts a single exact JSON block and known bounded visible Claude footer',()=>{
    expect(extractClaudeFencedIssueBody(fenced(RAW),true)).toBe(RAW);
    expect(extractClaudeFencedIssueBody(fenced(RAW,SESSION_SIGNATURE),true)).toBe(RAW);
    expect(parse(fenced(RAW,SESSION_SIGNATURE),true)).toEqual(parse(RAW));
    expect(parse(fenced(RAW,'\n'),true)).toEqual(parse(RAW));
    const windows=FENCE+'json\r\n'+RAW+'\r\n'+FENCE+SIGNATURE;
    expect(parse(windows,true)).toEqual(parse(RAW));
  });
  it('rejects multi-block, unexpected suffix, overlong footer and incomplete fences',()=>{
    for(const wrong of [
      fenced(RAW)+'\n'+fenced(RAW),
      fenced(RAW)+'\nmalicious',
      fenced(RAW)+'\n'+'x'.repeat(600),
      FENCE+'json\n'+RAW,
      fenced('',SIGNATURE),
      fenced(RAW,'\n\n---\n_Generated by [Unknown](https://claude.ai/code)_'),
      fenced(RAW,'\n\n---\n_Generated by [Claude Code](https://untrusted.example)_'),
    ]){
      expect(()=>parse(wrong,true)).toThrow(/REMOTE_BRIDGE_V2_BODY_FENCE_INVALID/);
    }
  });
  it('accepts JSON formatting but rejects duplicate keys and ambiguous lexical JSON',()=>{
    const pretty=JSON.stringify(JSON.parse(RAW),null,2);
    expect(parse(fenced(pretty,SIGNATURE),true)).toEqual(parse(RAW));
    expect(remoteBridgeRequestV2Digest(parse(fenced(pretty,SIGNATURE),true))).toBe(remoteBridgeRequestV2Digest(parse(RAW)));
    const duplicated=RAW.replace('"schema":','"schema":"FAKE","schema":');
    expect(()=>parse(fenced(duplicated,SIGNATURE),true)).toThrow(/REMOTE_BRIDGE_V2_BODY_FENCE_NONCANONICAL/);
    expect(()=>extractClaudeFencedIssueBody(fenced('{"value":1e3}'),true)).toThrow(/REMOTE_BRIDGE_V2_BODY_FENCE_NONCANONICAL/);
    const escapedNewline=JSON.stringify({value:'before\nand after'});
    expect(extractClaudeFencedIssueBody(fenced(escapedNewline),true)).toBe(escapedNewline);
  });
  it('never accepts text before the block or another language / malformed JSON',()=>{
    expect(()=>parse('hello\n'+fenced(RAW,SIGNATURE),true)).toThrow(/REMOTE_BRIDGE_V2_BODY_JSON_INVALID/);
    expect(()=>parse(FENCE+'javascript\n'+RAW+'\n'+FENCE,true)).toThrow(/REMOTE_BRIDGE_V2_BODY_JSON_INVALID/);
    expect(()=>parse(fenced('{bad json}',SIGNATURE),true)).toThrow(/REMOTE_BRIDGE_V2_BODY_JSON_INVALID/);
  });
  it('preserves author, repository, title and semantic field denials in opt-in mode',()=>{
    expect(()=>parseRemoteBridgeRequestV2({...BASE,body:fenced(RAW,SIGNATURE),allowClaudeFence:true,author:'attacker'})).toThrow(/REMOTE_BRIDGE_V2_AUTHOR_INVALID/);
    expect(()=>parseRemoteBridgeRequestV2({...BASE,body:fenced(RAW,SIGNATURE),allowClaudeFence:true,repository:'other/repo'})).toThrow(/REMOTE_BRIDGE_V2_REPOSITORY_INVALID/);
    expect(()=>parseRemoteBridgeRequestV2({...BASE,body:fenced(RAW,SIGNATURE),allowClaudeFence:true,title:'wrong'})).toThrow(/REMOTE_BRIDGE_V2_TITLE_INVALID/);
    const invalid=JSON.stringify({...JSON.parse(RAW),extra:'no'});
    expect(()=>parse(fenced(invalid,SIGNATURE),true)).toThrow(/REMOTE_BRIDGE_V2_FIELDS_INVALID/);
    const changed=JSON.stringify({...JSON.parse(RAW),operation:{kind:'HEALTH',action:'INVALID'}});
    expect(()=>parse(fenced(changed,SIGNATURE),true)).toThrow(/REMOTE_BRIDGE_V2_HEALTH_ACTION_INVALID/);
  });
});
